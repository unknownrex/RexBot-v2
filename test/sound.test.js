// Self-check for the sound-sticker encode patch. Run: npm test
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'
import ffmpegStatic from 'ffmpeg-static'
import { proto } from '@whiskeysockets/baileys'

const { patchSoundSticker, toOpus, audioFromVideo } = await import('../src/lib/sound.js')
const { CONFIG } = await import('../src/config.js')

// Field 26, wire type 2 -> tag varint 0xd2 0x01.
const TAG = Buffer.from([0xd2, 0x01])
const Sticker = proto.Message.StickerMessage

test('encode writes the audio field only when audio is set', () => {
  patchSoundSticker()
  const plain = Sticker.encode({ url: 'https://x', fileSha256: Buffer.alloc(32) }).finish()
  assert.equal(Buffer.from(plain).includes(TAG), false)

  const withAudio = Sticker.encode({
    url: 'https://x',
    fileSha256: Buffer.alloc(32),
    audioMessage: { url: 'https://y', mimetype: 'audio/ogg; codecs=opus', seconds: 3, ptt: false },
  }).finish()
  const buf = Buffer.from(withAudio)
  assert.ok(buf.includes(TAG), 'audio field missing from sticker payload')
  // Stock protobufjs ignores unknown field 26, so this must not throw.
  assert.equal(Sticker.decode(withAudio).url, 'https://x')
})

test('patching twice does not double the audio field', () => {
  patchSoundSticker()
  patchSoundSticker()
  const m = { audioMessage: { url: 'https://y', seconds: 1 } }
  const buf = Buffer.from(Sticker.encode(m).finish())
  assert.equal(buf.toString('hex').split(TAG.toString('hex')).length - 1, 1)
})

test('toOpus trims to the cap and emits Ogg', async () => {
  const wav = await sineWav(12)
  const { buffer, seconds } = await toOpus(wav, 5)
  assert.equal(buffer.subarray(0, 4).toString(), 'OggS')
  assert.ok(seconds <= 6, `clip is ${seconds}s, cap was 5s`)
})

// A tone long enough to prove the trim, generated by ffmpeg so no fixture file is needed.
function sineWav(seconds) {
  return new Promise((resolve, reject) => {
    const child = spawn(ffmpegStatic, ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', `sine=frequency=440:duration=${seconds}`, '-f', 'wav', 'pipe:1'])
    const chunks = []
    child.stdout.on('data', (d) => chunks.push(d))
    child.on('error', reject)
    child.on('close', (code) => (code === 0 ? resolve(Buffer.concat(chunks)) : reject(new Error(`ffmpeg ${code}`))))
  })
}

// Video carries audio only when the second lavfi input asks for it. Written to a
// temp file because the mp4 muxer refuses a non-seekable pipe.
async function testVideo(withAudio) {
  const file = path.join(tmpdir(), `sound-test-${withAudio ? 'a' : 'n'}-${process.pid}.mp4`)
  const input = ['-f', 'lavfi', '-i', 'testsrc=duration=3:size=128x128:rate=10']
  if (withAudio) input.push('-f', 'lavfi', '-i', 'sine=frequency=440:duration=3', '-c:a', 'aac', '-shortest')
  try {
    await new Promise((resolve, reject) => {
      const child = spawn(ffmpegStatic, ['-hide_banner', '-loglevel', 'error', '-y', ...input, '-c:v', 'libx264', file])
      let err = ''
      child.stderr.on('data', (d) => (err += d))
      child.on('error', reject)
      child.on('close', (code) => (code === 0 ? resolve() : reject(new Error(err.slice(0, 200)))))
    })
    return await readFile(file)
  } finally {
    await rm(file, { force: true })
  }
}

test("audioFromVideo uses the clip's own track", async () => {
  const { buffer, seconds } = await audioFromVideo(await testVideo(true))
  assert.equal(buffer.subarray(0, 4).toString(), 'OggS')
  assert.ok(seconds <= CONFIG.soundMaxSeconds, `clip is ${seconds}s, cap was ${CONFIG.soundMaxSeconds}`)
})

test('audioFromVideo reads a silent video as no audio', async () => {
  assert.equal(await audioFromVideo(await testVideo(false)), null)
})

// Videos ship without a size check before this change, so a busy clip went out
// over WhatsApp's 500 KB cap and could not be downloaded.
test('a busy video is compressed under the animated cap after packing', async () => {
  const { toSticker, webpDuration } = await import('../src/lib/sticker.js')
  const sticker = await toSticker(await busyVideo())
  assert.equal(sticker.animated, true)
  assert.ok(
    sticker.buffer.length <= CONFIG.animatedStickerMaxBytes,
    `sticker is ${Math.round(sticker.buffer.length / 1024)} KB, cap is ${CONFIG.animatedStickerMaxBytes / 1024} KB`,
  )
  console.log(`# busy video landed at ${Math.round(sticker.buffer.length / 1024)} KB`)
  assert.equal(sticker.buffer.subarray(8, 12).toString(), 'WEBP')
  // Length is the last thing the ladder gives up: a 10s source must survive as
  // a 10s sticker rather than being cut to fit the byte cap.
  const ms = await webpDuration(sticker.buffer)
  assert.ok(ms > 5000, `sticker was cut to ${(ms / 1000).toFixed(1)}s, expected the full clip`)
})

// High-entropy noise so every quality step fails and the ladder has to fall
// through frame rate and resolution to keep the full duration.
async function busyVideo() {
  const file = path.join(tmpdir(), `sound-busy-${process.pid}.mp4`)
  try {
    await new Promise((resolve, reject) => {
      const child = spawn(ffmpegStatic, [
        '-hide_banner', '-loglevel', 'error', '-y',
        '-f', 'lavfi', '-i', 'mandelbrot=size=512x512:rate=30',
        '-t', String(CONFIG.maxVideoSeconds), '-c:v', 'libx264', '-preset', 'ultrafast', file,
      ])
      let err = ''
      child.stderr.on('data', (d) => (err += d))
      child.on('error', reject)
      child.on('close', (code) => (code === 0 ? resolve() : reject(new Error(err.slice(0, 200)))))
    })
    return await readFile(file)
  } finally {
    await rm(file, { force: true })
  }
}
