export const displayWidth = (str) => {
  let total = 0
  for (const ch of String(str)) {
    const cp = ch.codePointAt(0)
    // Zero-width: variation selector (forces emoji presentation), ZWJ.
    if (cp === 0xfe0f || cp === 0xfe0e || cp === 0x200d) continue
    if (cp >= 0x0300 && cp <= 0x036f) continue // combining diacriticals
    total += WIDE.some(([lo, hi]) => cp >= lo && cp <= hi) ? 2 : 1
  }
  return total
}

export const renderHeader = (icon, title) => {
  const { style, accent, minWidth, maxWidth } = theme
  const label = `${icon} ${accent} ${String(title).toUpperCase()}`

  if (style === 'minimal') return `${icon} ${accent} *${String(title).toUpperCase()}*`

  const natural = displayWidth(label)
  const width = natural > maxWidth ? natural : Math.max(natural, minWidth)
  const rule = BOX.h.repeat(width + 2)
  return [
    BOX.tl + rule + BOX.tr,
    `${BOX.v} ${label}${' '.repeat(width - natural)} ${BOX.v}`,
    BOX.bl + rule + BOX.br,
  ].join('\n')
}

// Header + optional body, separated by a blank line. Returns the full text
// for a message or a media caption.
export const compose = (icon, title, body) => {
  const header = renderHeader(icon, title)
  const text = body == null ? '' : String(body).trim()
  return text ? `${header}\n\n${text}` : header
}

